import "server-only";
import { FormFieldType } from "@/generated/prisma/enums";
import type { Prisma } from "@/generated/prisma/client";
import { prisma } from "@/server/db/client";
import type { TenantContext } from "@/server/rbac/guards";

type Db = Prisma.TransactionClient;

const formFieldSelect = {
  id: true,
  label: true,
  name: true,
  type: true,
  required: true,
  placeholder: true,
  helpText: true,
  options: true,
  position: true,
} satisfies Prisma.FormFieldSelect;

const formWithFieldsInclude = {
  fields: { orderBy: { position: "asc" }, select: formFieldSelect },
} satisfies Prisma.FormInclude;

export type FormFieldDto = Prisma.FormFieldGetPayload<{ select: typeof formFieldSelect }>;

export type FormWithFields = Prisma.FormGetPayload<{ include: typeof formWithFieldsInclude }>;

export async function listForms(context: TenantContext, client: Db = prisma) {
  return client.form.findMany({
    where: { subAccountId: context.subAccountId },
    orderBy: { createdAt: "asc" },
    select: {
      id: true,
      publicId: true,
      name: true,
      status: true,
      submitLabel: true,
      successMessage: true,
      redirectUrl: true,
      consentText: true,
      notifyUserIds: true,
      autoTags: true,
      createdAt: true,
      updatedAt: true,
      _count: { select: { fields: true, submissions: true } },
    },
  });
}

export type FormListItem = Awaited<ReturnType<typeof listForms>>[number];

export async function findForm(
  context: TenantContext,
  formId: string,
  client: Db = prisma,
): Promise<FormWithFields | null> {
  return client.form.findFirst({
    where: { id: formId, subAccountId: context.subAccountId },
    include: formWithFieldsInclude,
  });
}

/**
 * Public lookup for the no-auth renderer. This is the one repository query
 * without a TenantContext by design — the only predicate is `ACTIVE` status,
 * and it must not leak drafts or paused forms to anonymous visitors.
 */
export async function findPublishedFormByPublicId(publicId: string, client: Db = prisma) {
  return client.form.findFirst({
    where: { publicId, status: "ACTIVE" },
    include: formWithFieldsInclude,
  });
}

export async function insertForm(
  context: TenantContext,
  formId: string, // generated by the service so the public slug can be retried atomically
  publicId: string,
  name: string,
  client: Db = prisma,
) {
  return client.form.create({
    data: {
      id: formId,
      subAccountId: context.subAccountId,
      publicId,
      name,
    },
    include: formWithFieldsInclude,
  });
}

export async function insertFormField(
  formId: string,
  data: {
    label: string;
    name: string;
    type: FormFieldType;
    required: boolean;
    placeholder: string | null;
    helpText: string | null;
    options: string[];
    position: number;
  },
  client: Db = prisma,
) {
  return client.formField.create({ data: { formId, ...data }, select: formFieldSelect });
}

export async function updateFormField(
  context: TenantContext,
  fieldId: string,
  data: {
    label: string;
    name: string;
    type: FormFieldType;
    required: boolean;
    placeholder: string | null;
    helpText: string | null;
    options: string[];
  },
  client: Db = prisma,
) {
  const field = await client.formField.findFirst({
    where: { id: fieldId, form: { subAccountId: context.subAccountId } },
    select: { id: true },
  });
  if (!field) {
    return null;
  }
  return client.formField.update({
    where: { id: fieldId },
    data,
    select: formFieldSelect,
  });
}

export async function deleteFormField(
  context: TenantContext,
  fieldId: string,
  client: Db = prisma,
): Promise<boolean> {
  const result = await client.formField.deleteMany({
    where: { id: fieldId, form: { subAccountId: context.subAccountId } },
  });
  return result.count > 0;
}

/**
 * Re-applies positions in list order (positions are plain ints, not unique,
 * so no temporary offset is needed).
 */
export async function reorderFormFields(
  formId: string,
  fieldIds: string[],
  client: Db = prisma,
) {
  await Promise.all(
    fieldIds.map((fieldId, index) =>
      client.formField.updateMany({ where: { id: fieldId, formId }, data: { position: index } }),
    ),
  );
}

export async function updateFormRow(
  context: TenantContext,
  formId: string,
  data: Prisma.FormUpdateInput,
  client: Db = prisma,
) {
  const form = await client.form.findFirst({
    where: { id: formId, subAccountId: context.subAccountId },
    select: { id: true },
  });
  if (!form) {
    return null;
  }
  return client.form.update({
    where: { id: formId },
    data,
    include: formWithFieldsInclude,
  });
}

export async function deleteFormRow(context: TenantContext, formId: string, client: Db = prisma) {
  const result = await client.form.deleteMany({
    where: { id: formId, subAccountId: context.subAccountId },
  });
  return result.count;
}

export async function insertFormSubmission(
  context: TenantContext,
  data: {
    formId: string;
    contactId: string | null;
    data: Prisma.InputJsonValue;
    honeypotTriggered: boolean;
    ipHash: string | null;
    userAgent: string | null;
    referrer: string | null;
    utmSource: string | null;
    utmMedium: string | null;
    utmCampaign: string | null;
    utmContent: string | null;
    utmTerm: string | null;
  },
  client: Db = prisma,
) {
  return client.formSubmission.create({
    data: { subAccountId: context.subAccountId, ...data },
  });
}

export async function listFormSubmissions(
  context: TenantContext,
  formId: string,
  client: Db = prisma,
) {
  return client.formSubmission.findMany({
    where: { formId, subAccountId: context.subAccountId },
    orderBy: { createdAt: "desc" },
    take: 100,
    include: {
      contact: { select: { id: true, firstName: true, lastName: true, email: true } },
    },
  });
}

export type FormSubmissionListItem = Awaited<ReturnType<typeof listFormSubmissions>>[number];

export async function listFormNotifyCandidates(context: TenantContext, client: Db = prisma) {
  const memberships = await client.subAccountMembership.findMany({
    where: { subAccountId: context.subAccountId, status: "ACTIVE" },
    select: { user: { select: { id: true, name: true, email: true } } },
    orderBy: { user: { name: "asc" } },
  });
  return memberships.map((membership) => membership.user);
}
